# 7. Списковые включения
# Списковое включение создаёт новый список:
#
# result = [выражение for элемент in коллекция]
# result = [выражение for элемент in коллекция if условие]
# Сначала реши задачу обычным циклом, затем перепиши через списковое включение.


# Задача 15. Квадраты чётных чисел
# Из чисел от 1 до 20 создай список квадратов только чётных чисел.
#
# Ожидаемое начало результата:
#
# [4, 16, 36, 64, ...]

# Вариант 1: обычный цикл
squares = []
for i in range(1, 20):
    squares.append(i ** 2)
print(squares)

# Вариант 2: списковое включение
result = [i ** 2 for i in range(1, 20)]
print(result)

# Задача 2. Поиск максимума без max()
# Даны размеры файлов в мегабайтах:
#
# sizes = [120, 45, 890, 310, 76]
# Найди самый большой размер с помощью цикла. Функцию max() использовать нельзя.
#
# Подсказка: сначала считай первый элемент текущим максимальным значением.

sizes = [120, 45, 890, 310, 76]

max_value = sizes[0];

# Найди максимальный размер
for size in sizes:
    if size > max_value:
        max_value = size
print(max_value)
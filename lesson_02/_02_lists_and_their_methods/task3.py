# Задача 3. Нумерация уведомлений
# Выведи уведомления с нумерацией, начинающейся с 1:
#
# 1. Новый комментарий
# 2. Файл загружен
# 3. Пароль изменён
# Используй enumerate().

notifications = ["Новый комментарий", "Файл загружен", "Пароль изменён"]

# Выведи нумерованный список
print(list(enumerate(notifications)))


